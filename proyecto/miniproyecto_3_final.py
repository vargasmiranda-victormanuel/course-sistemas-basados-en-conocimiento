# SECCIÓN 3: VISUALIZACIÓN DE LA TRAZA
# =============================================================================

def imprimir_traza(resultado):
    """
    Imprime la traza completa del razonamiento del motor de inferencia.
    Muestra cada regla disparada, los hechos usados, las reglas candidatas,
    el criterio de desempate aplicado y la decisión tomada en cada fase.
    """
    print("=" * 75)
    print(f"  DIAGNOSTICO CRM: {resultado['cliente']}")
    print(f"  Reglas evaluadas: {resultado['reglas_evaluadas']}")
    print("=" * 75)

    ciclo_actual = None
    fases = {
        1: "CARGA DE HECHOS",
        2: "INFERENCIA RFM (Segmentacion)",
        3: "INFERENCIA CUSTOMER JOURNEY",
        4: "EVALUACION DE RESTRICCIONES",
        5: "INFERENCIA DE ACCION CRM",
        6: "INFERENCIA DE CANAL",
        7: "RESULTADO FINAL"
    }

    for entrada in resultado["traza"]:
        # Encabezado de fase
        if entrada["ciclo"] != ciclo_actual:
            ciclo_actual = entrada["ciclo"]
            fase = fases.get(ciclo_actual, f"CICLO {ciclo_actual}")
            print(f"\n{'-' * 75}")
            print(f"  Ciclo {ciclo_actual}: {fase}")
            print(f"{'-' * 75}")

        tipo = entrada["tipo"]

        if tipo == "evento":
            print(f"  [{entrada['evento']}] {entrada.get('detalle', '')}")

        elif tipo == "regla_disparada":
            print(f"  REGLA ACTIVADA: {entrada['regla']}")
            print(f"     SI:       {entrada['condicion']}")
            print(f"     ENTONCES: {entrada['resultado']}")
            if entrada.get("detalle"):
                print(f"     DETALLE:  {entrada['detalle']}")

        elif tipo == "candidatas":
            nombres = ", ".join(entrada["candidatas"]) if entrada["candidatas"] else "(ninguna)"
            print(f"  CANDIDATAS ({entrada['fase']}, total={entrada['total']}): {nombres}")

        elif tipo == "resolucion":
            print(f"  RESOLUCION DE CONFLICTO:")
            print(f"     Regla elegida:      {entrada['regla_elegida']}")
            print(f"     Criterio aplicado:  {entrada['criterio']}")
            print(f"     Candidatas validas: {entrada['n_candidatas']}")
            if entrada.get("decision"):
                print(f"     Decision final:    {entrada['decision']}")

        elif tipo == "hecho_derivado":
            print(f"  HECHO DERIVADO: {entrada['hecho']}")
            print(f"     ORIGEN: {entrada['origen']}")

    # Resumen final
    print(f"\n{'=' * 75}")
    print(f"  DECISION FINAL")
    print(f"{'=' * 75}")
    print(f"  Accion:  {resultado['accion']}")
    print(f"  Tipo:    {resultado['tipo_accion']}")
    print(f"  Regla:   {resultado['regla_aplicada']}")
    print(f"  Canal:   {resultado['canal']}")
    print(f"{'=' * 75}")

    # Cadena de reglas
    reglas_disparadas = [e for e in resultado["traza"] if e["tipo"] == "regla_disparada"]
    print(f"\n  CADENA DE REGLAS EMPLEADA ({len(reglas_disparadas)} reglas disparadas):")
    for i, r in enumerate(reglas_disparadas, 1):
        print(f"     {i}. [{r['regla']}] SI {r['condicion']} -> {r['resultado']}")
    print()


