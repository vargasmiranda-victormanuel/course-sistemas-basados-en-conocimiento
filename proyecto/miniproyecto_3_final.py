class MotorInferencia:
    """
    Motor de inferencia con encadenamiento hacia adelante (forward chaining).

    El ciclo de inferencia sigue estos pasos:
      1. Cargar hechos iniciales del cliente
      2. Evaluar reglas RFM → derivar hecho: segmento
      3. Aplicar equivalencia → derivar hecho: nivel_rfm
      4. Evaluar reglas Customer Journey → derivar hecho: etapa
      5. Evaluar reglas negativas → derivar hechos: restricciones
      6. Evaluar reglas de acción → generar conjunto de conflicto
      7. Resolver conflictos → seleccionar acción ganadora
      8. Evaluar reglas de canal → derivar hecho: canal preferido

    Resolución de conflictos: en cada fase se detectan todas las reglas activas
    (candidatas), se determina el criterio de desempate (salience, y en empate
    por valor RFM o por orden de definición) y se registra la decisión tomada.
    Cada paso queda registrado en la traza para explicar el razonamiento.
    """

    def __init__(self):
        self.hechos = {}              # Memoria de trabajo (hechos derivados)
        self.traza = []               # Cadena de reglas disparadas
        self.reglas_evaluadas = 0     # Contador de reglas evaluadas
        self.ciclo = 0                # Número de ciclo del motor

    def registrar_hecho(self, clave, valor, origen):
        """Agrega un hecho a la memoria de trabajo y lo registra en la traza."""
        self.hechos[clave] = valor
        self.traza.append({
            "ciclo": self.ciclo,
            "tipo": "hecho_derivado",
            "hecho": f"{clave} = {valor}",
            "origen": origen
        })

    def registrar_regla(self, regla_nombre, condicion, resultado, detalle=""):
        """Registra la activación de una regla en la traza."""
        self.traza.append({
            "ciclo": self.ciclo,
            "tipo": "regla_disparada",
            "regla": regla_nombre,
            "condicion": condicion,
            "resultado": resultado,
            "detalle": detalle
        })

    def registrar_evento(self, evento, detalle=""):
        """Registra un evento del motor en la traza."""
        self.traza.append({
            "ciclo": self.ciclo,
            "tipo": "evento",
            "evento": evento,
            "detalle": detalle
        })

    def registrar_candidatas(self, candidatas, fase):
        """Registra el conjunto de reglas candidatas detectadas en una fase."""
        self.traza.append({
            "ciclo": self.ciclo,
            "tipo": "candidatas",
            "fase": fase,
            "candidatas": [r["nombre"] for r in candidatas],
            "total": len(candidatas)
        })

    def registrar_resolucion(self, regla_elegida, criterio, n_candidatas):
        """Registra la regla elegida tras aplicar el criterio de desempate."""
        self.traza.append({
            "ciclo": self.ciclo,
            "tipo": "resolucion",
            "regla_elegida": regla_elegida["nombre"],
            "criterio": criterio,
            "n_candidatas": n_candidatas,
            "decision": regla_elegida.get("entonces", "")
        })

    # -------------------------------------------------------------------------
    # Paso 1: Cargar hechos iniciales
    # -------------------------------------------------------------------------
    def cargar_hechos_iniciales(self, cliente):
        """Carga los hechos observables del cliente en la memoria de trabajo."""
        self.ciclo = 1
        self.registrar_evento("INICIO", f"Cargando hechos del cliente: {cliente.nombre}")

        # Hechos directos (observables)
        hechos_iniciales = {
            "nombre":                   cliente.nombre,
            "recency":                  cliente.rfm.recency,
            "frequency":                cliente.rfm.frequency,
            "monetary":                 cliente.rfm.monetary,
            "arquetipo":                cliente.arquetipo,
            "dias_desde_apertura":      cliente.dias_desde_apertura,
            "tendencia_transacciones":  cliente.tendencia_transacciones,
            "cancelacion_productos":    cliente.cancelacion_productos,
            "saldo_promedio":           cliente.saldo_promedio,
            "uso_tarjetas":             cliente.uso_tarjetas,
            "interacciones_digitales":  cliente.interacciones_digitales,
        }
        for clave, valor in hechos_iniciales.items():
            self.hechos[clave] = valor

        # Afinidades
        for cs in cliente.servicios:
            srv = CATALOGO_SERVICIOS.get(cs.servicio_id)
            if srv:
                clave = f"afinidad_{srv.nombre.lower().replace(' ', '_')}"
                self.hechos[clave] = cs.afinidad

        self.registrar_evento(
            "HECHOS_CARGADOS",
            f"{len(self.hechos)} hechos iniciales en memoria de trabajo"
        )

    # -------------------------------------------------------------------------
    # Paso 2: Inferir segmento RFM
    # -------------------------------------------------------------------------
    def inferir_segmento_rfm(self, cliente):
        """
        Evalúa todas las reglas RFM, detecta candidatas y selecciona la
        de mayor salience. En empate se respeta el orden de definición.
        """
        self.ciclo = 2
        self.registrar_evento("FASE_RFM", "Evaluando reglas de segmentación RFM")

        # Recolectar todas las reglas activas (candidatas)
        candidatas = []
        for regla in REGLAS_RFM:
            self.reglas_evaluadas += 1
            if regla["evaluar"](cliente.rfm):
                candidatas.append(regla)

        self.registrar_candidatas(candidatas, "RFM")

        # Ordenar por salience desc; en empate se mantiene el orden de definición
        candidatas_ord = sorted(candidatas, key=lambda r: r["salience"], reverse=True)
        ganadora = candidatas_ord[0]

        # Determinar criterio de desempate
        max_sal = ganadora["salience"]
        empate = [r for r in candidatas_ord if r["salience"] == max_sal]
        if len(candidatas) == 1:
            criterio = "unica regla activada"
        elif len(empate) == 1:
            criterio = f"salience (mayor: {max_sal})"
        else:
            criterio = f"salience + orden_definicion (salience={max_sal})"

        self.registrar_resolucion(ganadora, criterio, len(candidatas))

        # Registrar activación y derivar hecho
        cliente.rfm.segmento = ganadora["segmento"]
        self.registrar_regla(
            ganadora["nombre"],
            ganadora["si"],
            ganadora["entonces"],
            f"Hechos usados: R={cliente.rfm.recency}, F={cliente.rfm.frequency}, M={cliente.rfm.monetary} | salience={max_sal}"
        )
        self.registrar_hecho("segmento_rfm", ganadora["segmento"], ganadora["nombre"])

        # Equivalencia (sección 5.1.5)
        nivel = EQUIVALENCIA_RFM.get(cliente.rfm.segmento, "Bajo")
        cliente.nivel_rfm = nivel
        self.registrar_hecho("nivel_rfm", nivel, f"Equivalencia: {cliente.rfm.segmento} → {nivel}")

    # -------------------------------------------------------------------------
    # Paso 3: Inferir Customer Journey
    # -------------------------------------------------------------------------
    def inferir_customer_journey(self, cliente):
        """
        Evalúa todas las reglas de Journey, detecta candidatas y selecciona la
        de mayor salience. En empate se respeta el orden de definición.
        """
        self.ciclo = 3
        self.registrar_evento("FASE_JOURNEY", "Evaluando reglas de Customer Journey")

        # Recolectar todas las reglas activas (candidatas)
        candidatas = []
        for regla in REGLAS_JOURNEY:
            self.reglas_evaluadas += 1
            if regla["evaluar"](cliente):
                candidatas.append(regla)

        self.registrar_candidatas(candidatas, "Journey")

        # Ordenar por salience desc; en empate se mantiene el orden de definición
        candidatas_ord = sorted(candidatas, key=lambda r: r["salience"], reverse=True)
        ganadora = candidatas_ord[0]

        # Determinar criterio de desempate
        max_sal = ganadora["salience"]
        empate = [r for r in candidatas_ord if r["salience"] == max_sal]
        if len(candidatas) == 1:
            criterio = "unica regla activada"
        elif len(empate) == 1:
            criterio = f"salience (mayor: {max_sal})"
        else:
            criterio = f"salience + orden_definicion (salience={max_sal})"

        self.registrar_resolucion(ganadora, criterio, len(candidatas))

        # Registrar activación y derivar hecho
        cliente.customer_journey = ganadora["etapa"]
        self.registrar_regla(
            ganadora["nombre"],
            ganadora["si"],
            ganadora["entonces"],
            f"Hechos usados: días={cliente.dias_desde_apertura}, "
            f"transacc={cliente.tendencia_transacciones}, "
            f"cancel={cliente.cancelacion_productos}, "
            f"saldo={cliente.saldo_promedio}, "
            f"tarjetas={cliente.uso_tarjetas}, "
            f"digital={cliente.interacciones_digitales} | salience={max_sal}"
        )
        self.registrar_hecho("customer_journey", ganadora["etapa"], ganadora["nombre"])

    # -------------------------------------------------------------------------
    # Paso 4: Evaluar restricciones (reglas negativas)
    # -------------------------------------------------------------------------
    def evaluar_restricciones(self, cliente):
        """
        Evalúa todas las reglas negativas y registra las restricciones activas.
        Las restricciones se aplican de forma acumulativa (no hay elección entre
        ellas): todas las activadas imponen su bloqueo.
        """
        self.ciclo = 4
        self.registrar_evento("FASE_RESTRICCIONES", "Evaluando reglas negativas")

        restricciones = []
        for regla in REGLAS_NEGATIVAS:
            self.reglas_evaluadas += 1
            if regla["evaluar"](cliente):
                restricciones.append(regla)
                self.registrar_regla(
                    regla["nombre"],
                    regla["si"],
                    regla["entonces"]
                )
                self.registrar_hecho(
                    f"restriccion_{regla['nombre']}",
                    regla["entonces"],
                    regla["nombre"]
                )

        # Registrar candidatas y criterio de acumulación
        self.registrar_candidatas(restricciones, "Restricciones")
        if restricciones:
            self.registrar_resolucion(
                {"nombre": ", ".join(r["nombre"] for r in restricciones),
                 "entonces": "Todas aplican de forma acumulativa"},
                "acumulacion (todas las activadas aplican)",
                len(restricciones)
            )
        else:
            self.registrar_evento("SIN_RESTRICCIONES", "No se activaron reglas negativas")

        return restricciones

    # -------------------------------------------------------------------------
    # Paso 5: Evaluar reglas de acción y resolver conflictos
    # -------------------------------------------------------------------------
    def inferir_accion(self, cliente, restricciones):
        """
        Evalúa reglas de acción, genera conjunto de conflicto y lo resuelve.
        Estrategia de resolución (sección Resolución de Conflictos del doc):
          1. Detectar todas las reglas activas (candidatas)
          2. Filtrar reglas bloqueadas por restricciones
          3. Ordenar por salience (mayor salience = mayor prioridad)
          4. En empate de salience, priorizar por valor del cliente (RFM)
          5. En empate, respetar orden de definición
        """
        self.ciclo = 5
        self.registrar_evento("FASE_ACCION", "Evaluando reglas de acción CRM")

        # Generar conjunto de conflicto (todas las reglas activadas)
        conjunto_conflicto = []
        for regla in REGLAS_ACCION:
            self.reglas_evaluadas += 1
            if regla["evaluar"](cliente):
                conjunto_conflicto.append(regla)
                self.registrar_regla(
                    regla["nombre"],
                    regla["si"],
                    regla["entonces"],
                    f"salience={regla['salience']}"
                )

        self.registrar_evento(
            "CONJUNTO_CONFLICTO",
            f"{len(conjunto_conflicto)} regla(s) activada(s)"
        )

        # Registrar candidatas antes del filtrado
        self.registrar_candidatas(conjunto_conflicto, "Accion")

        if not conjunto_conflicto:
            accion_default = "Comunicación informativa general según afinidad más alta"
            self.registrar_evento("ACCION_DEFAULT", accion_default)
            self.registrar_hecho("accion_crm", accion_default, "DEFAULT (ninguna regla activada)")
            return {"nombre": "DEFAULT", "entonces": accion_default, "tipo_accion_id": 1}

        # Filtrar por restricciones
        def esta_bloqueada(regla):
            for neg in restricciones:
                for palabra in neg.get("palabras_bloqueadas", []):
                    if palabra.lower() in regla["entonces"].lower():
                        return True
            return False

        reglas_validas = []
        reglas_bloqueadas = []
        for r in conjunto_conflicto:
            if esta_bloqueada(r):
                reglas_bloqueadas.append(r)
            else:
                reglas_validas.append(r)

        for rb in reglas_bloqueadas:
            self.registrar_evento(
                "REGLA_BLOQUEADA",
                f"{rb['nombre']}: '{rb['entonces']}' bloqueada por restriccion"
            )

        if not reglas_validas:
            accion_default = "Comunicación informativa general (todas bloqueadas por restricciones)"
            self.registrar_evento("TODAS_BLOQUEADAS", accion_default)
            self.registrar_hecho("accion_crm", accion_default, "DEFAULT (restricciones)")
            return {"nombre": "DEFAULT", "entonces": accion_default, "tipo_accion_id": 1}

        # Resolver conflicto: ordenar por salience desc, luego por valor RFM
        reglas_validas.sort(key=lambda r: (
            r["salience"],
            PRIORIDAD_RFM.get(cliente.nivel_rfm, 0)
        ), reverse=True)

        ganadora = reglas_validas[0]

        # Determinar criterio de desempate
        max_sal = ganadora["salience"]
        empate_sal = [r for r in reglas_validas if r["salience"] == max_sal]
        if len(reglas_validas) == 1:
            criterio = "unica regla valida tras filtrado"
        elif len(empate_sal) == 1:
            criterio = f"salience (mayor: {max_sal})"
        else:
            prio_rfm = PRIORIDAD_RFM.get(cliente.nivel_rfm, 0)
            empate_rfm = [r for r in empate_sal
                          if PRIORIDAD_RFM.get(cliente.nivel_rfm, 0) == prio_rfm]
            if len(empate_rfm) < len(empate_sal):
                criterio = f"salience + valor_rfm (salience={max_sal}, rfm={cliente.nivel_rfm})"
            else:
                criterio = f"salience + valor_rfm + orden_definicion (salience={max_sal})"

        self.registrar_resolucion(ganadora, criterio, len(reglas_validas))

        if len(reglas_validas) > 1:
            self.registrar_evento(
                "RESOLUCION_CONFLICTO",
                f"Se priorizo {ganadora['nombre']} (salience={ganadora['salience']}) "
                f"sobre {', '.join(r['nombre'] for r in reglas_validas[1:])}"
            )

        tipo = TipoAccionCRM.obtener(ganadora["tipo_accion_id"])
        self.registrar_hecho("accion_crm", ganadora["entonces"], ganadora["nombre"])
        self.registrar_hecho("tipo_accion", tipo["nombre"], ganadora["nombre"])

        return ganadora

    # -------------------------------------------------------------------------
    # Paso 6: Inferir canal preferido
    # -------------------------------------------------------------------------
    def inferir_canal(self, cliente):
        """
        Evalúa todas las reglas de canal, detecta candidatas y selecciona la
        de mayor salience. En empate se respeta el orden de definición.
        """
        self.ciclo = 6
        self.registrar_evento("FASE_CANAL", "Evaluando reglas de canal preferido")

        canales_activados = []
        for regla in REGLAS_CANAL:
            self.reglas_evaluadas += 1
            if regla["evaluar"](cliente):
                canales_activados.append(regla)
                self.registrar_regla(
                    regla["nombre"],
                    regla["si"],
                    f"Canal={regla['entonces']}",
                    f"salience={regla['salience']}"
                )

        self.registrar_candidatas(canales_activados, "Canal")

        if canales_activados:
            # Ordenar por salience desc; en empate se mantiene el orden de definición
            canales_ord = sorted(canales_activados, key=lambda r: r["salience"], reverse=True)
            principal = canales_ord[0]

            # Determinar criterio de desempate
            max_sal = principal["salience"]
            empate = [r for r in canales_ord if r["salience"] == max_sal]
            if len(canales_activados) == 1:
                criterio = "unica regla activada"
            elif len(empate) == 1:
                criterio = f"salience (mayor: {max_sal})"
            else:
                criterio = f"salience + orden_definicion (salience={max_sal})"

            self.registrar_resolucion(principal, criterio, len(canales_activados))

            cliente.canal_preferido = [r["entonces"] for r in canales_ord]
            self.registrar_hecho("canal_principal", principal["entonces"], principal["nombre"])
        else:
            self.registrar_resolucion(
                {"nombre": "DEFAULT", "entonces": "Digital (default)"},
                "ninguna regla activada", 0
            )
            cliente.canal_preferido = ["Digital (default)"]
            self.registrar_hecho("canal_principal", "Digital (default)", "DEFAULT")

    # -------------------------------------------------------------------------
    # Ejecutar ciclo completo de inferencia
    # -------------------------------------------------------------------------
    def ejecutar(self, cliente):
        """
        Ejecuta el ciclo completo de inferencia con forward chaining.
        Retorna el resultado del diagnóstico y la traza completa.
        """
        # Reset estado del motor
        self.hechos = {}
        self.traza = []
        self.reglas_evaluadas = 0
        self.ciclo = 0

        # Ciclo de inferencia
        self.cargar_hechos_iniciales(cliente)       # Ciclo 1: Hechos
        self.inferir_segmento_rfm(cliente)          # Ciclo 2: RFM → Segmento
        self.inferir_customer_journey(cliente)       # Ciclo 3: Journey → Etapa
        restricciones = self.evaluar_restricciones(cliente)  # Ciclo 4: Restricciones
        accion = self.inferir_accion(cliente, restricciones) # Ciclo 5: Acción
        self.inferir_canal(cliente)                  # Ciclo 6: Canal

        self.ciclo = 7
        self.registrar_evento("FIN", "Inferencia completada")

        return {
            "cliente": cliente.nombre,
            "hechos": dict(self.hechos),
            "accion": accion["entonces"],
            "tipo_accion": TipoAccionCRM.obtener(accion.get("tipo_accion_id", 1))["nombre"],
            "regla_aplicada": accion["nombre"],
            "canal": cliente.canal_preferido[0] if cliente.canal_preferido else "N/A",
            "traza": list(self.traza),
            "reglas_evaluadas": self.reglas_evaluadas,
        }


